/* marketing-pull -- PURE. A fixed, reproducible twelve-card showcase.

   It exists for local captures, not as an alternate game pull: the fixed
   lineup deliberately ignores the weighted odds and is never banked. Each
   rarity band gets two cards so a single view can show the full card system.
   Handles are preferences; if a creator is absent from a refreshed set, the
   largest real channel in that same band fills the slot. */

import { RARITY_ORDER, toCount } from './core.js';

export const MARKETING_SHAPE = Object.freeze({
  RUBY: 2, UR: 2, SSR: 2, SR: 2, R: 2, N: 2,
});

const DISPLAY_ORDER = Object.freeze([...RARITY_ORDER].reverse());
const norm = value => String(value ?? '').trim().toLowerCase();
const subsOf = card => toCount(card?.channel?.subscriberCount);
const isAutoGenerated = card => / - topic$/.test(norm(card?.channel?.title));

/* Preferred names, grouped by rarity band. These all resolve in the current
   local Core Set snapshot; fallback selection keeps the capture usable after
   a future set refresh changes its contents. */
export const MARKETING_ROSTER = Object.freeze([
  '@mrbeast', '@pewdiepie',
  '@cristiano', '@taylorswift',
  '@rihanna', '@markiplier',
  '@charlidamelio', '@moresidemen',
  '@jerma985', '@mizkif',
  '@jblow888', '@therealghetts',
]);

const DISPLAY_TITLES = Object.freeze({
  '@cristiano': 'Cristiano Ronaldo',
  '@charlidamelio': "Charli D'Amelio",
});

function fallbackOrder(pool) {
  return pool
    .filter(card => !isAutoGenerated(card) && subsOf(card) > 0)
    .sort((a, b) => subsOf(b) - subsOf(a));
}

export function marketingPull(cards, { shape = MARKETING_SHAPE, roster = MARKETING_ROSTER } = {}) {
  const byBand = new Map();
  for (const card of cards ?? []) {
    if (!byBand.has(card.rarity)) byBand.set(card.rarity, []);
    byBand.get(card.rarity).push(card);
  }

  const rank = new Map(roster.map((handle, i) => [norm(handle), i]));
  const rankOf = card => rank.get(norm(card?.channel?.handle));
  const picked = [];
  const used = new Set();

  const take = card => {
    if (!card || used.has(card.channel.id)) return false;
    used.add(card.channel.id);
    const title = DISPLAY_TITLES[norm(card.channel.handle)];
    picked.push(title ? { ...card, channel: { ...card.channel, title } } : card);
    return true;
  };

  for (const rarity of DISPLAY_ORDER) {
    const want = shape[rarity] ?? 0;
    if (!want) continue;
    const pool = byBand.get(rarity) ?? [];
    const named = pool
      .filter(card => rankOf(card) !== undefined)
      .sort((a, b) => rankOf(a) - rankOf(b));

    let filled = 0;
    for (const card of [...named, ...fallbackOrder(pool)]) {
      if (filled >= want) break;
      if (take(card)) filled += 1;
    }
  }

  /* A short or missing tier can occur in a custom local set. Top up to twelve
     with distinct real cards, keeping the ordinary Core Set's balanced lineup. */
  const total = Object.values(shape).reduce((sum, count) => sum + count, 0);
  if (picked.length < total) {
    for (const card of fallbackOrder(cards ?? [])) {
      if (picked.length >= total) break;
      take(card);
    }
  }

  return picked;
}
